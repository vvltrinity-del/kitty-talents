package com.kittytalents.breeding;

import com.kittytalents.entity.CatVariant;
import com.kittytalents.entity.ProductionTier;
import com.kittytalents.entity.TalentedCat;
import net.minecraft.world.item.ItemStack;

/**
 * Enforces the architectural separation between:
 * 1. Breed / Feline Identity (Visual species & anatomical identity)
 * 2. Cosmetic Skin (Visual texture overlay 0..16)
 * 3. Production Tier (Resource progression: Standard -> Netherite)
 * 4. Production Type (Actual resource generated)
 * 5. Biological Gender (Male ♂ / Female ♀, immutable except via Gender Ribbon)
 * 6. Mutations (E.g. Nekomata twin tails)
 */
public final class FelineGenetics {

    public enum Gender {
        MALE("Male", "♂"),
        FEMALE("Female", "♀");

        private final String displayName;
        private final String symbol;

        Gender(String displayName, String symbol) {
            this.displayName = displayName;
            this.symbol = symbol;
        }

        public String getDisplayName() { return displayName; }
        public String getSymbol() { return symbol; }

        public static Gender fromBoolean(boolean isFemale) {
            return isFemale ? FEMALE : MALE;
        }
    }

    /**
     * Confirms that changing cosmetic skin does not modify production tier, variant or gender.
     */
    public static void applySkinSafely(TalentedCat cat, int newSkinId) {
        if (cat == null) return;
        CatVariant variantBefore = cat.getCatVariant();
        ProductionTier tierBefore = cat.getProductionTier();
        boolean femaleBefore = cat.isFemale();

        cat.setSkinId(newSkinId);

        // Verification invariants:
        assert cat.getCatVariant() == variantBefore : "Skin change corrupted cat variant!";
        assert cat.getProductionTier() == tierBefore : "Skin change corrupted production tier!";
        assert cat.isFemale() == femaleBefore : "Skin change corrupted gender!";
    }

    /**
     * Resolves resource generated by a cat without conflating visual skin/breed with production tier.
     */
    public static ItemStack resolveProductionOutput(CatVariant variant, ProductionTier tier) {
        if (tier != null && tier != ProductionTier.STANDARD) {
            return tier.getProductionResult();
        }
        if (variant != null && variant.isProductive()) {
            return variant.getProductionResult();
        }
        return tier != null ? tier.getProductionResult() : ItemStack.EMPTY;
    }

    private FelineGenetics() {}
}
