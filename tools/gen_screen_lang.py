"""Regenerate the companion screen's en_us.json block ("gui.kittytalents.screen.*") from the Java call sites.

Usage: python tools/gen_screen_lang.py
Collects every KTText.t/s("key", "fallback") literal plus the table-driven keys (tabs, categories, slots, skins,
stats, presets, controls), then replaces the generated block at the end of en_us.json. Idempotent.
"""
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
GUI = ROOT / "src/main/java/com/kittytalents/client/gui"
LANG = ROOT / "src/main/resources/assets/kittytalents/lang/en_us.json"
PREFIX = "gui.kittytalents.screen."
BEGIN = '  "_comment.screen": "Generated by tools/gen_screen_lang.py",'

STR = r'"((?:[^"\\]|\\.)*)"'


def unescape(s):
    return json.loads('"' + s + '"')


def string_array(src, name):
    m = re.search(name + r"\s*=\s*\{([^}]*)\}", src, re.S)
    return [unescape(x) for x in re.findall(STR, m.group(1))] if m else []


entries = {}
sources = {p.name: p.read_text(encoding="utf-8") for p in list(GUI.glob("CatTalentScreen.java")) + list((GUI / "tab").glob("*.java"))}

for src in sources.values():
    for key, fallback in re.findall(r"KTText\.[ts]\(\s*" + STR + r"\s*,\s*" + STR, src):
        entries[unescape(key)] = unescape(fallback)

shell = sources["CatTalentScreen.java"]
for k, n in zip(string_array(shell, "tabKeys"), string_array(shell, "tabNames")):
    entries["tab." + k] = n

talents = sources["TalentsTab.java"]
for k, n in zip(string_array(talents, "CATEGORY_KEYS"), string_array(talents, "CATEGORY_NAMES")):
    entries["talents.cat." + k] = n

for k, n in re.findall(r"new SlotDef\(\d+, " + STR + ", " + STR, sources["GearTab.java"]):
    entries["gear.slot." + unescape(k)] = unescape(n)

style = sources["StyleTab.java"]
for k, n in zip(string_array(style, r"String\[\] keys"), string_array(style, r"String\[\] names")):
    entries["style." + k] = n
for i, n in enumerate(string_array(style, "SKIN_NAMES")):
    entries["style.skin." + str(i)] = n

for k, n in re.findall(r"new Stat\(" + STR + ", " + STR, sources["StatsTab.java"]):
    entries["stats." + unescape(k)] = unescape(n)

for k, n in re.findall(r"\{\s*" + STR + ",\s*" + STR + r",\s*\"[a-z_]+\",", sources["CombatTab.java"]):
    entries["combat.preset." + unescape(k)] = unescape(n)

for k, _key, desc in re.findall(r"\{\s*" + STR + ",\s*" + STR + ",\s*" + STR + r"\s*\}", sources["TwineTab.java"]):
    entries["twine.control." + unescape(k)] = unescape(desc)

text = LANG.read_text(encoding="utf-8")
if BEGIN in text:
    text = text[: text.index(BEGIN)].rstrip()
    text = text.rstrip(",")
else:
    text = text.rstrip()
    assert text.endswith("}")
    text = text[:-1].rstrip()

lines = [BEGIN] + ["  " + json.dumps(PREFIX + k) + ": " + json.dumps(v, ensure_ascii=False) + "," for k, v in sorted(entries.items())]
lines[-1] = lines[-1].rstrip(",")
text = text + ",\n\n" + "\n".join(lines) + "\n}\n"
json.loads(text)  # must stay valid JSON
LANG.write_text(text, encoding="utf-8")
print(f"{len(entries)} screen keys written")
